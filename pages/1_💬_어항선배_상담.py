import streamlit as st
import random

st.set_page_config(page_title="어항 선배 상담소", page_icon="💬", layout="wide")

st.title("💬 가상 어항 선배의 족집게 Q&A 상담소")
st.caption("어항 관리, 합사, 물잡이 등 물고기를 키우며 궁금했던 점을 선배에게 물어보세요!")

st.markdown("---")

# 선배 프로필 영역
col1, col2 = st.columns([1, 4])
with col1:
    st.markdown("<h1 style='text-align: center; font-size: 80px;'>👨‍🌾</h1>", unsafe_allow_html=True)
with col2:
    st.subheader("안녕하세요! 10년 차 물생활 어항 선배입니다 🐟")
    st.write("어항 물이 갑자기 흐려졌나요? 물고기가 구석에만 있나요? 무엇이든 편하게 물어보세요!")

st.markdown("---")

# 자주 묻는 질문 챗봇형 선택
question = st.selectbox(
    "💡 어떤 내용이 궁금하신가요? 질문을 선택하거나 직접 입력해 보세요!",
    [
        "선택해 주세요",
        "❓ 어항 세팅할 때 '물잡이'가 뭔가요? 얼마나 해야 하나요?",
        "❓ 어항 백탁 현상(물이 쌀뜨물처럼 흐려짐)은 왜 생기나요?",
        "❓ 물고기가 어항 구석이나 바닥에 가만히 있어요.",
        "❓ 환수(물 갈아주기)는 얼마나 자주, 어떻게 해야 하나요?",
        "✍️ 직접 질문 입력하기"
    ]
)

if question == "✍️ 직접 질문 입력하기":
    user_custom_q = st.text_input("어항 선배에게 궁금한 점을 직접 적어보세요:")
    if st.button("선배에게 질문하기") and user_custom_q:
        responses = [
            f"선배의 조언: '{user_custom_q}'에 대해 고민이 많으시군요! 기본적으로 수온과 여과기 상태를 먼저 점검해 보시는 걸 추천합니다. 물고기 행동을 유심히 관찰해 보세요!",
            f"선배의 조언: 좋은 질문입니다! 보통 수질 변화나 여과력 부족이 원인일 수 있어요. 환수를 20% 정도 진행해 보시는 건 어떨까요?",
            f"선배의 조언: 초보 사육자들이 자주 겪는 상황이에요! 당황하지 마시고 사료 급여량을 줄이고 수온을 일정하게 유지해 주세요."
        ]
        st.success(random.choice(responses))

elif question != "선택해 주세요":
    st.markdown("### 👨‍🏫 어항 선배의 답변")
    if "물잡이" in question:
        st.info("💧 **물잡이란?** 어항에 물고기가 살 수 있도록 박테리아(여과균) 생태계를 만드는 과정입니다.\n\n- **기간**: 최소 1주 ~ 2주일 권장\n- **방법**: 어항에 물과 여과기를 켜두고 박테리아제를 넣은 뒤 기다립니다.")
    elif "백탁" in question:
        st.warning("🫧 **백탁 현상 원인**: 여과 박테리아가 아직 자리 잡지 못해 폭증하거나 사료 잔반으로 미생물이 급증했기 때문입니다.\n\n- **대처법**: 사료를 1~2일 끊고, 여과기를 계속 돌리면서 기다리면 자연스럽게 투명해집니다.")
    elif "가만히" in question:
        st.error("🤒 **물고기 이상 행동**: 수온 변화 스트레스, 쇼크, 또는 백점병 등 초기 질병 증상일 수 있습니다.\n\n- **대처법**: 현재 수온이 최적 범위인지 확인하고 지느러미에 하얀 점이 없는지 관찰하세요.")
    elif "환수" in question:
        st.success("🪣 **올바른 환수법**: 일주일에 1~2회, 전체 물의 **20~30%**만 부분 환수해 주는 것이 기본입니다.\n\n- **주의사항**: 받아둔 수돗물(염소 제거)을 사용하고, 기존 어항 물과 **수온을 똑같이 맞추어** 넣어야 쇼크가 없습니다.")
